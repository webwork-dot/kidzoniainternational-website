            clickable: true,
          },
          navigation: {
            nextEl: '.swiper-button-next',
            prevEl: '.swiper-button-prev',
          },
          autoplay: {
            delay: 5000,
          },
          slidesPerView: 1,
          spaceBetween: 10,
        });
      });
    }
  });
